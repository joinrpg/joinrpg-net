namespace JoinRpg.Domain.CharacterFields;

/// <summary>
/// Как сохранять значения полей.
/// </summary>
public enum FieldSaveMode
{
    /// <summary>
    /// Обычное сохранение: обязательные поля не дают себя очистить, пустым полям генерируются
    /// значения по умолчанию.
    /// </summary>
    Normal,

    /// <summary>
    /// Восстановление уже бывших значений — из выгрузки мастера после потери данных (DRP, #5529).
    /// Значения записываются ровно как были: пустое обязательное поле не ошибка (в выгрузке его могло
    /// и не быть заполнено — например, поле стало обязательным позже), а значения по умолчанию не
    /// генерируются (их не было), выключенные варианты списков разрешены (вариант могли выключить уже после
    /// того, как его выбрали). Права мастера на поле и проверка самих значений (вариант принадлежит полю)
    /// остаются в силе.
    /// </summary>
    Restore,
}
