    /// <summary>Полное имя субрегиона («Санкт-Петербург»).</summary>
    public static string GetName(this Region region) => GetNames(region).Name;

    /// <summary>Короткое имя субрегиона для бейджей и узких мест («СПб»).</summary>
    public static string GetShortName(this Region region) => GetNames(region).ShortName;

    /// <summary>Имя макрорегиона («Северо-Запад»).</summary>
    public static string GetName(this MacroRegion macroRegion) => macroRegion switch
    {
        MacroRegion.NorthWest => "Северо-Запад",
        MacroRegion.MoscowAndCenter => "Москва и Центральный регион",
        MacroRegion.Ural => "Урал",
        MacroRegion.Siberia => "Сибирь",
        MacroRegion.South => "Юг России",
        MacroRegion.FarEast => "Дальний Восток",
        MacroRegion.Volga => "Поволжье",
        MacroRegion.Ukraine => "Украина",
        MacroRegion.Belarus => "Беларусь",
        MacroRegion.Kazakhstan => "Казахстан",
        MacroRegion.Foreign => "Зарубежье",
        _ => throw new ArgumentOutOfRangeException(nameof(macroRegion), macroRegion, "Неизвестный макрорегион КогдаИгры"),
    };

    private static (string Name, string ShortName) GetNames(Region region)
        => regionNames.TryGetValue(region, out var names)
            ? names
            : throw new ArgumentOutOfRangeException(nameof(region), region, "Неизвестный субрегион КогдаИгры");
