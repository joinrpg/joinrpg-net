namespace JoinRpg.Data.Interfaces;

/// <summary>
/// Чем кончилась вставка восстановленного комментария к заявке (DRP, #5492).
/// </summary>
public enum RestoredCommentInsertResult
{
    /// <summary>Комментарий вставлен — с заданным идентификатором или, если его нет, с новым.</summary>
    Inserted = 0,

    /// <summary>
    /// Комментарий уже есть в обсуждении этой заявки: с тем же идентификатором, а без идентификатора —
    /// с тем же автором, временем и текстом. Ничего не сделано.
    /// </summary>
    AlreadyExists = 1,

    /// <summary>Идентификатор занят комментарием другого обсуждения — ничего не сделано.</summary>
    TakenElsewhere = 2,

    /// <summary>
    /// Идентификатор не ниже текущего значения счётчика IDENTITY (или счётчик не прочитан): это не
    /// потерянный комментарий — потерянные лежат строго ниже счётчика. Ничего не сделано.
    /// </summary>
    NotLostId = 3,
}
