namespace JoinRpg.Data.Interfaces;

/// <summary>
/// Чем кончилась вставка восстановленного комментария к заявке (DRP, #5492) или финансовой операции
/// (DRP, #5561): у операции идентификатор тот же, что у её комментария.
/// </summary>
public enum RestoredCommentInsertResult
{
    /// <summary>Комментарий вставлен — с заданным идентификатором или, если его нет, с новым.</summary>
    Inserted = 0,

    /// <summary>
    /// Комментарий уже есть в обсуждении этой заявки: с тем же идентификатором, а без идентификатора —
    /// с тем же автором, временем и текстом (у финансовой операции — с тем же автором, видом, суммой и
    /// временем в пределах минуты). Ничего не сделано.
    /// </summary>
    AlreadyExists = 1,

    /// <summary>
    /// Идентификатор занят комментарием другого обсуждения — ничего не сделано.
    /// </summary>
    TakenElsewhere = 2,

    /// <summary>
    /// Идентификатор не ниже текущего значения счётчика IDENTITY (или счётчик не прочитан): это не
    /// потерянный комментарий — потерянные лежат строго ниже счётчика. Ничего не сделано.
    /// </summary>
    NotLostId = 3,

    /// <summary>
    /// Идентификатор занят комментарием этого же обсуждения без операции — например, возвращённым
    /// инструментами DRP: операция и банковские реквизиты дописаны к существующему комментарию,
    /// его текст не тронут.
    /// </summary>
    Attached = 4,
}
