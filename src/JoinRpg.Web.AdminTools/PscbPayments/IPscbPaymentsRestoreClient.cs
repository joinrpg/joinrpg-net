using JoinRpg.XGameApi.Contract.Pscb;

namespace JoinRpg.Web.AdminTools.PscbPayments;

/// <summary>
/// Восстановление потерянных платежей ПСКБ (ADR027).
/// </summary>
/// <remarks>
/// Отдельный клиент рядом с <see cref="IPscbPaymentsClient"/> — по соглашению островов на каждую
/// панель свой клиент. Запрос — те же параметры периода, что у списка: восстановление заново
/// скачивает диапазон и работает от свежих данных банка, а не от того, что прислал клиент;
/// суммы и даты из клиентского JSON не берутся никогда.
/// </remarks>
public interface IPscbPaymentsRestoreClient
{
    /// <summary>
    /// Восстанавливает потерянные строки периода, которым сверка вынесла вердикт «можно
    /// восстановить автоматически». Строки, которые восстановить нельзя, остаются в таблице
    /// с причиной; отказ всего прогона (банк не вернул список, записей больше лимита) приходит
    /// исключением, а не результатом.
    /// </summary>
    Task<PscbRestoreResult> Restore(PscbPaymentsQuery query);
}
