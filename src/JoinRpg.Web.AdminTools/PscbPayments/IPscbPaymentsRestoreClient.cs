using JoinRpg.XGameApi.Contract.Pscb;

namespace JoinRpg.Web.AdminTools.PscbPayments;

/// <summary>
/// Восстановление потерянных платежей ПСКБ (ADR027).
/// </summary>
/// <remarks>
/// Отдельный клиент рядом с <see cref="IPscbPaymentsClient"/> — по соглашению островов на каждую
/// панель свой клиент. Запрос — те же параметры периода, что у списка, плюс <c>orderId</c> строки:
/// восстановление заново скачивает диапазон и работает от свежих данных банка, а не от того,
/// что прислал клиент; суммы и даты из клиентского JSON не берутся никогда.
/// </remarks>
public interface IPscbPaymentsRestoreClient
{
    /// <summary>
    /// Восстанавливает одну строку периода, которой сверка вынесла вердикт «можно восстановить
    /// автоматически». Один запрос — одна строка в своей области DI: упавшая строка не отравляет
    /// следующую, иначе общая <c>DbContext</c> несла бы в трекере грязную заявку. Сервер каждый
    /// раз заново скачивает период, поэтому прогон из N строк стоит N скачиваний — сознательно,
    /// надёжность важнее скорости. Отказ всего прогона (банк не вернул список, сверка не удалась,
    /// нет админских прав) приходит исключением, а исход строки — результатом.
    /// </summary>
    Task<PscbRestoreRowResult> RestoreRow(PscbRestoreRowRequest request);
}
